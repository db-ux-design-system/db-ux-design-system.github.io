/**
 * Visual Library Optimize Script
 *
 * Normalizes and optimizes all SVG sources in `template/visuals/` with SVGO and regenerates
 * the typed registry `template/visuals/index.ts`.
 *
 * Usage:
 *   node scripts/visuals/optimize-visuals.ts          # write optimized files + registry
 *   node scripts/visuals/optimize-visuals.ts --check  # write nothing, exit 1 if files would change
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { optimize } from 'svgo';
import { visualsSvgoConfig, visualWarnings } from './svgo.config.ts';

const ROOT = resolve(import.meta.dirname, '..', '..');
const VISUALS_DIR = join(ROOT, 'template', 'visuals');
const REGISTRY_PATH = join(VISUALS_DIR, 'index.ts');
const FILE_NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*\.svg$/;

const checkOnly = process.argv.includes('--check');

/** `product-management` → `visualProductManagement` (prefix keeps names starting with a digit valid) */
function toIdentifier(name: string): string {
	return `visual-${name}`.replace(/-([a-z0-9])/g, (_match, char: string) => char.toUpperCase());
}

function buildRegistry(names: string[]): string {
	// Match Prettier's `quoteProps: 'as-needed'`: quote only keys that are no valid identifier
	const key = (name: string) => (/^[a-z][a-z0-9]*$/.test(name) ? name : `'${name}'`);
	const lines = [
		'// Generated by `pnpm run visuals:optimize` – do not edit manually.',
		...names.map((name) => `import ${toIdentifier(name)} from './${name}.svg?raw';`),
		'',
		'export const visuals = {',
		...names.map((name) => `\t${key(name)}: ${toIdentifier(name)},`),
		'} as const;',
		'',
		'export type VisualName = keyof typeof visuals;',
		'',
	];
	if (names.length === 0) {
		// Keep the registry valid without any visual
		return [
			'// Generated by `pnpm run visuals:optimize` – do not edit manually.',
			'export const visuals: Record<never, string> = {};',
			'',
			'export type VisualName = keyof typeof visuals;',
			'',
		].join('\n');
	}
	return lines.join('\n');
}

const files = readdirSync(VISUALS_DIR)
	.filter((file) => file.endsWith('.svg'))
	.sort();

const invalidNames = files.filter((file) => !FILE_NAME_PATTERN.test(file));
if (invalidNames.length > 0) {
	console.error(
		`❌ Invalid visual file names (use kebab-case, e.g. "product-management.svg"): ${invalidNames.join(', ')}`,
	);
	process.exit(1);
}

// `icon-2.svg` and `icon2.svg` both map to `visualIcon2` – the registry would not compile
const filesByIdentifier = new Map<string, string[]>();
for (const file of files) {
	const identifier = toIdentifier(file.replace(/\.svg$/, ''));
	filesByIdentifier.set(identifier, [...(filesByIdentifier.get(identifier) ?? []), file]);
}
const collisions = [...filesByIdentifier].filter(([, group]) => group.length > 1);
if (collisions.length > 0) {
	console.error(
		`❌ Visual file names map to the same registry identifier, rename one of them:\n  ${collisions
			.map(([identifier, group]) => `${group.join(', ')} → ${identifier}`)
			.join('\n  ')}`,
	);
	process.exit(1);
}

const changed: string[] = [];

for (const file of files) {
	const path = join(VISUALS_DIR, file);
	const source = readFileSync(path, 'utf8');
	let result: string;
	try {
		result = optimize(source, { ...visualsSvgoConfig, path }).data;
	} catch (error) {
		console.error(`❌ ${file}: ${error instanceof Error ? error.message : String(error)}`);
		process.exit(1);
	}
	if (result !== source) {
		changed.push(`template/visuals/${file}`);
		if (!checkOnly) writeFileSync(path, result);
	}
}

const registry = buildRegistry(files.map((file) => file.replace(/\.svg$/, '')));
const currentRegistry = existsSync(REGISTRY_PATH) ? readFileSync(REGISTRY_PATH, 'utf8') : '';
if (registry !== currentRegistry) {
	changed.push('template/visuals/index.ts');
	if (!checkOnly) writeFileSync(REGISTRY_PATH, registry);
}

for (const warning of visualWarnings) {
	console.warn(`⚠️  ${warning}`);
}

if (checkOnly) {
	if (changed.length > 0) {
		console.error(
			`❌ Visuals are not normalized. Run \`pnpm run visuals:optimize\`:\n  ${changed.join('\n  ')}`,
		);
		process.exit(1);
	}
	console.log(`✅ ${files.length} visual(s) normalized, registry up to date.`);
} else {
	console.log(
		changed.length > 0
			? `✅ Updated:\n  ${changed.join('\n  ')}`
			: `✅ ${files.length} visual(s) already normalized.`,
	);
}
