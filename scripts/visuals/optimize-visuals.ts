/**
 * Visual Library Optimize Script
 *
 * Normalizes and optimizes all SVG sources in `template/visuals/` with SVGO and regenerates
 * the typed registry `template/visuals/index.ts`.
 *
 * It also regenerates `template/visuals/images.ts`, the typed registry of the raster visuals in
 * `static/assets/teasers/`. Those PNGs are served as static files, so they are only listed by
 * name – nothing is read or optimized here.
 *
 * Usage:
 *   node scripts/visuals/optimize-visuals.ts          # write optimized files + registries
 *   node scripts/visuals/optimize-visuals.ts --check  # write nothing, exit 1 if files would change
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { optimize } from 'svgo';
import { visualsSvgoConfig, visualWarnings } from './svgo.config.ts';

const ROOT = resolve(import.meta.dirname, '..', '..');
const VISUALS_DIR = join(ROOT, 'template', 'visuals');
const REGISTRY_PATH = join(VISUALS_DIR, 'index.ts');
const IMAGES_DIR = join(ROOT, 'static', 'assets', 'teasers');
const IMAGES_REGISTRY_PATH = join(VISUALS_DIR, 'images.ts');
const FILE_NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*\.svg$/;
const IMAGE_FILE_NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*\.png$/;

const checkOnly = process.argv.includes('--check');

/** `product-management` → `visualProductManagement` (prefix keeps names starting with a digit valid) */
function toIdentifier(name: string): string {
	return `visual-${name}`.replace(/-([a-z0-9])/g, (_match, char: string) => char.toUpperCase());
}

function buildRegistry(names: string[]): string {
	// Match Prettier's `quoteProps: 'as-needed'`: quote only keys that are no valid identifier
	const key = (name: string) => (/^[a-z][a-z0-9]*$/.test(name) ? name : `'${name}'`);
	const lines = [
		'// Generated by `pnpm run optimize:visuals` – do not edit manually.',
		...names.map((name) => `import ${toIdentifier(name)} from './${name}.svg?raw';`),
		'',
		'export const visuals = {',
		...names.map((name) => `\t${key(name)}: ${toIdentifier(name)},`),
		'} as const;',
		'',
		'export type VisualName = keyof typeof visuals;',
		'',
	];
	if (names.length === 0) {
		// Keep the registry valid without any visual
		return [
			'// Generated by `pnpm run optimize:visuals` – do not edit manually.',
			'export const visuals: Record<never, string> = {};',
			'',
			'export type VisualName = keyof typeof visuals;',
			'',
		].join('\n');
	}
	return lines.join('\n');
}

/**
 * Registry of the raster visuals. They live in `static/assets/teasers/` and are served as static
 * files, so only the names are listed – the component builds the URL from the name.
 */
function buildImagesRegistry(names: string[]): string {
	const lines = [
		'// Generated by `pnpm run optimize:visuals` – do not edit manually.',
		'',
		'/** PNG visuals in `static/assets/teasers/`, by file name without the extension. */',
		'export const visualImages = [',
		...names.map((name) => `\t'${name}',`),
		'] as const;',
		'',
		'export type VisualImageName = (typeof visualImages)[number];',
		'',
	];
	if (names.length === 0) {
		// Keep the registry valid without any raster visual
		return [
			'// Generated by `pnpm run optimize:visuals` – do not edit manually.',
			'',
			'/** PNG visuals in `static/assets/teasers/`, by file name without the extension. */',
			'export const visualImages: readonly string[] = [];',
			'',
			'export type VisualImageName = never;',
			'',
		].join('\n');
	}
	return lines.join('\n');
}

const files = readdirSync(VISUALS_DIR)
	.filter((file) => file.endsWith('.svg'))
	.sort();

const invalidNames = files.filter((file) => !FILE_NAME_PATTERN.test(file));
if (invalidNames.length > 0) {
	console.error(
		`❌ Invalid visual file names (use kebab-case, e.g. "product-management.svg"): ${invalidNames.join(', ')}`,
	);
	process.exit(1);
}

// `icon-2.svg` and `icon2.svg` both map to `visualIcon2` – the registry would not compile
const filesByIdentifier = new Map<string, string[]>();
for (const file of files) {
	const identifier = toIdentifier(file.replace(/\.svg$/, ''));
	filesByIdentifier.set(identifier, [...(filesByIdentifier.get(identifier) ?? []), file]);
}
const collisions = [...filesByIdentifier].filter(([, group]) => group.length > 1);
if (collisions.length > 0) {
	console.error(
		`❌ Visual file names map to the same registry identifier, rename one of them:\n  ${collisions
			.map(([identifier, group]) => `${group.join(', ')} → ${identifier}`)
			.join('\n  ')}`,
	);
	process.exit(1);
}

const changed: string[] = [];

for (const file of files) {
	const path = join(VISUALS_DIR, file);
	const source = readFileSync(path, 'utf8');
	let result: string;
	try {
		result = optimize(source, { ...visualsSvgoConfig, path }).data;
	} catch (error) {
		console.error(`❌ ${file}: ${error instanceof Error ? error.message : String(error)}`);
		process.exit(1);
	}
	if (result !== source) {
		changed.push(`template/visuals/${file}`);
		if (!checkOnly) writeFileSync(path, result);
	}
}

const registry = buildRegistry(files.map((file) => file.replace(/\.svg$/, '')));
const currentRegistry = existsSync(REGISTRY_PATH) ? readFileSync(REGISTRY_PATH, 'utf8') : '';
if (registry !== currentRegistry) {
	changed.push('template/visuals/index.ts');
	if (!checkOnly) writeFileSync(REGISTRY_PATH, registry);
}

// Raster visuals: only the registry of names, the PNGs themselves stay untouched
const imageFiles = existsSync(IMAGES_DIR)
	? readdirSync(IMAGES_DIR)
			.filter((file) => file.toLowerCase().endsWith('.png'))
			.sort()
	: [];

const invalidImageNames = imageFiles.filter((file) => !IMAGE_FILE_NAME_PATTERN.test(file));
if (invalidImageNames.length > 0) {
	console.error(
		'❌ Invalid raster visual file names in static/assets/teasers (use lowercase kebab-case, ' +
			`e.g. "product-management.png"): ${invalidImageNames.join(', ')}`,
	);
	process.exit(1);
}

const imagesRegistry = buildImagesRegistry(imageFiles.map((file) => file.replace(/\.png$/, '')));
const currentImagesRegistry = existsSync(IMAGES_REGISTRY_PATH)
	? readFileSync(IMAGES_REGISTRY_PATH, 'utf8')
	: '';
if (imagesRegistry !== currentImagesRegistry) {
	changed.push('template/visuals/images.ts');
	if (!checkOnly) writeFileSync(IMAGES_REGISTRY_PATH, imagesRegistry);
}

for (const warning of visualWarnings) {
	console.warn(`⚠️  ${warning}`);
}

if (checkOnly) {
	if (changed.length > 0) {
		console.error(
			`❌ Visuals are not normalized. Run \`pnpm run optimize:visuals\`:\n  ${changed.join('\n  ')}`,
		);
		process.exit(1);
	}
	console.log(
		`✅ ${files.length} visual(s) normalized, ${imageFiles.length} raster visual(s) registered, ` +
			'registries up to date.',
	);
} else {
	console.log(
		changed.length > 0
			? `✅ Updated:\n  ${changed.join('\n  ')}`
			: `✅ ${files.length} visual(s) already normalized, ` +
					`${imageFiles.length} raster visual(s) registered.`,
	);
}
